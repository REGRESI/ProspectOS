"""M7: LinkedIn content strategy planner and plan-driven post drafts.

- A plan (goal, audience, 3–4 pillars, posts per week, 6 weeks) is generated by the LLM
  as strictly formatted lines and parsed; nothing is published.
- Per plan item, a ``content_post`` job writes two variants in the author's voice (voice
  profile settings + up to 5 style examples). The result becomes a normal Social Studio
  post draft (variant A as caption, both variants in studio_context) and goes through
  the existing approval and image flow.
- Publishing: the official LinkedIn path stays capability-gated. Otherwise the user copies
  the text, posts in LinkedIn and marks the post ``published_manually`` — a separate state
  that is never shown as a provider publication.
"""

