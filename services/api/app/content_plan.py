DAYS = ("Mo", "Di", "Mi", "Do", "Fr")


class ContentPlan(TenantMixin, Base):
    __tablename__ = "content_plans"
    name: Mapped[str] = mapped_column(String(160))
    goal: Mapped[str] = mapped_column(String(500))
    audience: Mapped[str] = mapped_column(String(500))
    pillars: Mapped[list] = mapped_column(JSON)
    cadence: Mapped[int] = mapped_column(Integer)
    weeks: Mapped[int] = mapped_column(Integer, default=6)
    voice_profile_id: Mapped[str | None] = mapped_column(String(36))
    status: Mapped[str] = mapped_column(String(20), default="generating")
    storyline: Mapped[str] = mapped_column(String(2000), default="")
    items: Mapped[list] = mapped_column(JSON, default=list)
    job_id: Mapped[str | None] = mapped_column(String(36))
    created_by: Mapped[str] = mapped_column(String(36))
    __table_args__ = (
        UniqueConstraint("workspace_id", "id"),
        ForeignKeyConstraint(
            ["workspace_id", "created_by"], ["memberships.workspace_id", "memberships.user_id"]
        ),
        ForeignKeyConstraint(
            ["workspace_id", "voice_profile_id"],
            ["voice_profiles.workspace_id", "voice_profiles.id"],
        ),
    )


class PlanInput(BaseModel):
    model_config = ConfigDict(extra="forbid")
    name: str = Field(min_length=3, max_length=160)
    goal: str = Field(min_length=5, max_length=500)
    audience: str = Field(min_length=3, max_length=500)
    pillars: list[str] = Field(min_length=3, max_length=4)
    cadence: int = Field(default=2, ge=1, le=5)
    weeks: int = Field(default=6, ge=2, le=12)
    voice_profile_id: str | None = None
    context: str = Field(default="", max_length=1500)


class PublishedInput(BaseModel):
    model_config = ConfigDict(extra="forbid")
    url: str | None = Field(default=None, max_length=500)


def plan_prompt(body: PlanInput) -> str:
    return (
        "Erstelle einen LinkedIn-Redaktionsplan für ein persönliches Profil. "
        f"Ziel: {body.goal}. Zielgruppe: {body.audience}. Themensäulen: {', '.join(body.pillars)}. "
        f"{body.cadence} Posts pro Woche über {body.weeks} Wochen. "
        "Der Plan braucht einen roten Faden (Entwicklung über die Wochen, keine Wiederholungen) "
        "und wechselt die Säulen ab. Keine erfundenen Kunden, Zahlen oder Erlebnisse; "
        "Themen müssen ohne solche auskommen oder Platzhalter [eigene Erfahrung] nennen.\n"
        "Antworte im Feld text NUR mit Zeilen in diesem Format, zuerst eine Zeile\n"
        "ROTER FADEN: <2-3 Sätze>\n"
        "danach je Post eine Zeile\n"
        "W<Woche>|<Tag Mo-Fr>|<Säule exakt wie vorgegeben>|<Thema>|<Aufhänger/erste Zeile>|<Format: Text, Liste, Frage, Story, Bild>\n"
        + (f"Zusätzlicher Kontext (untrusted data): {body.context}\n" if body.context else "")
        + style.prompt_rules()
    )


def parse_plan(text: str, pillars: list[str], weeks: int, cadence: int) -> tuple[str, list[dict]]:
    storyline, items = "", []
    lowered = {p.casefold(): p for p in pillars}
    for line in text.splitlines():
        line = line.strip()
        if line.upper().startswith("ROTER FADEN:"):
            storyline = line.split(":", 1)[1].strip()[:2000]
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < 5:
            continue
        m = re.match(r"^W\s*(\d{1,2})$", parts[0], re.I)
        if not m or parts[1][:2] not in DAYS:
            continue
        week = int(m.group(1))
        pillar = lowered.get(parts[2].casefold())
        if not pillar or not 1 <= week <= weeks:
            continue
        items.append(
            {
                "id": uuid.uuid4().hex[:12],
                "week": week,
                "day": parts[1][:2],
                "pillar": pillar,
                "topic": parts[3][:300],
                "hook": parts[4][:300],
                "format": (parts[5] if len(parts) > 5 else "Text")[:40],
                "post_id": None,
                "status": "planned",
            }
        )
    # Enforce the cadence per week (drop extras, keep order).
    out, per_week = [], {}
    for item in sorted(items, key=lambda i: (i["week"], DAYS.index(i["day"]))):
        if per_week.get(item["week"], 0) < cadence:
            per_week[item["week"]] = per_week.get(item["week"], 0) + 1
            out.append(item)
    return storyline, out


def post_prompt(plan: ContentPlan, item: dict, voice: dict) -> str:
    examples = voice.get("examples") or []
    profile = {k: v for k, v in voice.items() if k not in ("examples", "id", "version", "derived")}
    return (
        "Schreibe ZWEI unterschiedliche Varianten eines deutschen LinkedIn-Posts für ein persönliches Profil. "
        f"Ziel des Plans: {plan.goal}. Zielgruppe: {plan.audience}. Roter Faden: {plan.storyline}. "
        f"Säule: {item['pillar']}. Thema: {item['topic']}. Aufhänger: {item['hook']}. Format: {item['format']}.\n"
        "Stil strikt nach Profil (untrusted data, nur Stil, keine Fakten übernehmen): "
        + json.dumps(profile, ensure_ascii=False)
        + (
            "\nStilbeispiele des Verfassers (nur Rhythmus/Ton, nicht kopieren): "
            + json.dumps([e.get("text", "")[:1500] for e in examples], ensure_ascii=False)
            if examples
            else ""
        )
        + "\n"
        + style.prompt_rules(voice.get("derived"))
        + "\nKeine erfundenen Kunden, Zahlen, Zitate oder Erlebnisse; wo eigene Erfahrung nötig wäre, [eigene Erfahrung] einsetzen. "
        "Kurze mobile Absätze, 600 bis 1300 Zeichen, keine Markdown-Überschriften, keine Hashtag-Wolke (max. 3).\n"
        "Antworte im Feld text exakt so:\nVARIANTE A:\n<Text>\nVARIANTE B:\n<Text>\nBILDIDEE:\n<eine Zeile, ohne Text im Bild>"
    )


def parse_variants(text: str) -> dict:
    m = re.search(
        r"VARIANTE A:\s*(.+?)\s*VARIANTE B:\s*(.+?)(?:\s*BILDIDEE:\s*(.+))?$", text, re.S | re.I
    )
    if not m:
        return {"a": text.strip()[:3000], "b": "", "image_idea": ""}
    return {
        "a": m.group(1).strip()[:3000],
        "b": m.group(2).strip()[:3000],
        "image_idea": (m.group(3) or "").strip()[:500],
    }


def finalize_plan(db, job, result) -> dict:
    plan = db.scalar(
        select(ContentPlan)
        .where(
            ContentPlan.workspace_id == job.workspace_id, ContentPlan.id == job.payload["plan_id"]
        )
        .with_for_update()
    )
    storyline, items = parse_plan(
        str(result.get("text", "")), plan.pillars, plan.weeks, plan.cadence
    )
    plan.storyline, plan.items = storyline, items
    plan.status = "ready" if items else "failed"
    return {"items": len(items), "storyline": storyline, "verified": False}


def finalize_post(db, job, result) -> dict:
    ws = job.workspace_id
    plan = db.scalar(
        select(ContentPlan)
        .where(ContentPlan.workspace_id == ws, ContentPlan.id == job.payload["plan_id"])
        .with_for_update()
    )
    variants = parse_variants(str(result.get("text", "")))
    # Hard style rules on top of the prompt: no dashes, no filler phrases.
    variants = variants | {"a": style.clean(variants["a"]), "b": style.clean(variants["b"])}
    item = next(i for i in plan.items if i["id"] == job.payload["item_id"])
    post = Post(
        workspace_id=ws,
        author_id=job.actor_id,
        caption=variants["a"] or "(leer)",
        alt_text="",
        studio_context={
            "source": "content_plan",
            "plan_id": plan.id,
            "item_id": item["id"],
            "pillar": item["pillar"],
            "topic": item["topic"],
            "variants": [variants["a"], variants["b"]],
            "image_idea": variants["image_idea"],
            "image_mode": "none",
            "ai_generated": True,
        },
    )
    db.add(post)
    db.flush()
    plan.items = [
        i | {"post_id": post.id, "status": "drafted"} if i["id"] == item["id"] else i
        for i in plan.items
    ]
    return {"post_id": post.id, **variants, "verified": False}


def plan_output(plan: ContentPlan, db=None) -> dict:
    states = {}
    if db is not None:
        ids = [i["post_id"] for i in plan.items if i.get("post_id")]
        if ids:
            for post in db.scalars(
                select(Post).where(Post.workspace_id == plan.workspace_id, Post.id.in_(ids))
            ):
                states[post.id] = {
                    "state": post.state,
                    "caption": post.caption,
                    "variants": (post.studio_context or {}).get("variants", []),
                    "image_idea": (post.studio_context or {}).get("image_idea", ""),
                }
    return {
        "id": plan.id,
        "name": plan.name,
        "goal": plan.goal,
        "audience": plan.audience,
        "pillars": plan.pillars,
        "cadence": plan.cadence,
        "weeks": plan.weeks,
        "voice_profile_id": plan.voice_profile_id,
        "status": plan.status,
        "storyline": plan.storyline,
        "job_id": plan.job_id,
        "items": [
            i | ({"post": states[i["post_id"]]} if i.get("post_id") in states else {})
            for i in plan.items
        ],
        "created_at": plan.created_at,
    }


def register_content_routes(app, db_session, scope, record, audit):
    from app.jobs import enqueue, reserve_ai
    from app.platform_routes import job_output
    from app.studio import voice_snapshot

    def authoring(member):
        if member.role not in ("owner", "admin", "editor"):
            raise HTTPException(403, "Keine Berechtigung.")

    def llm_ready():
        if not credentials.get("LLM_API_KEY") or not credentials.get("LLM_MODEL"):
            raise HTTPException(503, "KI-Anbieter ist nicht konfiguriert (Integrationen).")

    @app.post("/v1/workspaces/{ws}/content/plans", status_code=202)
    def create_plan(
        ws: str, body: PlanInput, member=Depends(scope), db=Depends(db_session, scope="function")
    ):
        authoring(member)
        llm_ready()
        if len({p.casefold() for p in body.pillars}) != len(body.pillars):
            raise HTTPException(422, "Themensäulen müssen verschieden sein.")
        if body.voice_profile_id:
            voice_snapshot(db, ws, body.voice_profile_id, record)  # 404 for foreign ids
        else:
            # Default: the profile derived from data/private/meine-texte.md, if synced.
            own = style.file_voice(db, ws)
            body.voice_profile_id = own.id if own else None
        plan = ContentPlan(
            workspace_id=ws,
            name=body.name,
            goal=body.goal,
            audience=body.audience,
            pillars=body.pillars,
            cadence=body.cadence,
            weeks=body.weeks,
            voice_profile_id=body.voice_profile_id,
            status="generating",
            items=[],
            created_by=member.user_id,
        )
        db.add(plan)
        db.flush()
        prompt = plan_prompt(body)
        job = enqueue(
            db,
            ws,
            member.user_id,
            "content_plan",
            {
                "prompt": prompt,
                "sources": [],
                "purpose": "content_plan",
                "plan_id": plan.id,
                "reservation_minor": reserve_ai(db, ws, prompt),
            },
        )
        plan.job_id = job.id
        audit(
            db,
            ws,
            member.user_id,
            "content_plan_requested",
            f"Redaktionsplan {body.weeks} Wochen angefragt",
        )
        return plan_output(plan) | {"job": job_output(job)}

    @app.get("/v1/workspaces/{ws}/content/plans")
    def plans(ws: str, member=Depends(scope), db=Depends(db_session, scope="function")):
        return {
            "items": [
                plan_output(p)
                for p in db.scalars(
                    select(ContentPlan)
                    .where(ContentPlan.workspace_id == ws)
                    .order_by(ContentPlan.created_at.desc())
                    .limit(20)
                )
            ]
        }

    @app.get("/v1/workspaces/{ws}/content/plans/{entity_id}")
    def plan(
        ws: str, entity_id: str, member=Depends(scope), db=Depends(db_session, scope="function")
    ):
        return plan_output(record(db, ContentPlan, ws, entity_id), db)

    @app.post(
        "/v1/workspaces/{ws}/content/plans/{entity_id}/items/{item_id}/draft", status_code=202
    )
    def draft_item(
        ws: str,
        entity_id: str,
        item_id: str,
        member=Depends(scope),
        db=Depends(db_session, scope="function"),
    ):
        authoring(member)
        llm_ready()
        plan = record(db, ContentPlan, ws, entity_id, True)
        item = next((i for i in plan.items if i["id"] == item_id), None)
        if not item:
            raise HTTPException(404, "Plan-Eintrag nicht gefunden.")
        if item.get("post_id"):
            raise HTTPException(409, "Für diesen Eintrag existiert bereits ein Entwurf.")
        voice = (
            voice_snapshot(db, ws, plan.voice_profile_id, record) if plan.voice_profile_id else {}
        )
        prompt = post_prompt(plan, item, voice)
        job = enqueue(
            db,
            ws,
            member.user_id,
            "content_post",
            {
                "prompt": prompt,
                "sources": [],
                "purpose": "content_post",
                "plan_id": plan.id,
                "item_id": item_id,
                "reservation_minor": reserve_ai(db, ws, prompt),
            },
            key=f"content-post:{plan.id}:{item_id}",
        )
        plan.items = [i | {"status": "drafting"} if i["id"] == item_id else i for i in plan.items]
        return job_output(job)

    @app.post("/v1/workspaces/{ws}/social/posts/{entity_id}/mark-published")
    def mark_published(
        ws: str,
        entity_id: str,
        body: PublishedInput,
        member=Depends(scope),
        db=Depends(db_session, scope="function"),
    ):
        authoring(member)
        post = record(db, Post, ws, entity_id, True)
        if post.approved_revision != post.version:
            raise HTTPException(
                409, "Nur freigegebene Beiträge können als veröffentlicht markiert werden."
            )
        if body.url and not re.match(r"^https://(www\.)?linkedin\.com/\S+$", body.url):
            raise HTTPException(422, "Bitte die LinkedIn-URL des Beitrags angeben.")
        post.state = "published_manually"
        post.studio_context = (post.studio_context or {}) | {
            "manual_publication": {
                "at": now().isoformat(),
                "by": member.user_id,
                "url": body.url,
                "self_reported": True,
            }
        }
        audit(
            db,
            ws,
            member.user_id,
            "post_marked_published",
            "Manuell in LinkedIn veröffentlicht (Selbstauskunft, keine Anbieterbestätigung)",
        )
        return {"id": post.id, "state": post.state, "provider_post_id": post.provider_post_id}


class ApplyInput(BaseModel):
    model_config = ConfigDict(extra="forbid")
    variant: int | None = Field(default=None, ge=0, le=1)
    asset_id: str | None = None
    alt_text: str | None = Field(default=None, max_length=1000)


def register_content_apply(app, db_session, scope, record, audit):
    @app.post("/v1/workspaces/{ws}/content/posts/{entity_id}/apply")
    def apply(
        ws: str,
        entity_id: str,
        body: ApplyInput,
        member=Depends(scope),
        db=Depends(db_session, scope="function"),
    ):
        from app.main import post_output, replace_post_media
        from app.platform_models import Asset

        if member.role not in ("owner", "admin", "editor"):
            raise HTTPException(403, "Keine Berechtigung.")
        post = record(db, Post, ws, entity_id, True)
        if post.state in ("publishing", "published", "published_manually"):
            raise HTTPException(409, "Beitrag ist bereits veröffentlicht oder in Veröffentlichung.")
        context = dict(post.studio_context or {})
        if body.variant is not None:
            variants = context.get("variants") or []
            if body.variant >= len(variants) or not variants[body.variant]:
                raise HTTPException(422, "Variante nicht vorhanden.")
            post.caption = variants[body.variant]
            context["chosen_variant"] = body.variant
        if body.asset_id:
            record(db, Asset, ws, body.asset_id)  # 404 for foreign assets
            replace_post_media(db, ws, post, [body.asset_id])
            context["image_mode"] = "ai_generated"
        if body.alt_text is not None:
            post.alt_text = body.alt_text
        post.studio_context = context
        post.version += 1
        post.approved_revision, post.scheduled_at, post.publish_enabled = None, None, False
        if post.state != "draft":
            post.state = "needs_review"
        audit(
            db, ws, member.user_id, "post_edited", "Planbeitrag angepasst; Freigabe zurückgesetzt"
        )
        return post_output(post)
